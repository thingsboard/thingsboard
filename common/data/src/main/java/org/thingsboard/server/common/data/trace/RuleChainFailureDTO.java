package org.thingsboard.server.common.data.trace;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@JsonInclude(JsonInclude.Include.NON_NULL)
@Schema(description = "Rule Chain failure statistics")
public class RuleChainFailureDTO {
    @Schema(description = "Rule Chain name", example = "Root Rule Chain", required = true)
    private String ruleChainName;

    @Schema(description = "UUID of the rule chain (only available when log level is HEAVY)", example = "123e4567-e89b-12d3-a456-426614174000", nullable = true)
    private String ruleChainId;

    @Schema(description = "Number of distinct failed traces (error_count > 0) containing spans from this rule chain", example = "15", required = true)
    private long failedTraceCount;

    @Schema(description = "Total number of spans from this rule chain across all failed traces", example = "45", required = true)
    private long totalSpanCount;
}
